function renderLinks(links) {
  return links
    .map((link) =>
      link.url
        ? `<a class="link-chip" href="${link.url}" target="_blank" rel="noreferrer">${link.label}</a>`
        : `<span class="link-chip link-chip--muted">${link.label}</span>`
    )
    .join("");
}

function renderStatuses(statuses) {
  if (!statuses || statuses.length === 0) return "";

  return `
    <div class="project-card__status-list">
      ${statuses
        .map((status) => {
          const value = status.url
            ? `<a href="${status.url}" target="_blank" rel="noreferrer">${status.value}</a>`
            : status.value;
          return `
            <div class="status-row">
              <span>${status.label}</span>
              <strong>${value}</strong>
            </div>
          `;
        })
        .join("")}
    </div>
  `;
}

